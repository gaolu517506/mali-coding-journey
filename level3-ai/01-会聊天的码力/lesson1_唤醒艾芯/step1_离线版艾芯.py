# 第 1 课 · 唤醒前的调试（步骤 1）：离线版艾芯
# 艾芯还在卫星里沉睡。先用最原始的办法造一个"规则版艾芯"：
# 你说关键词，它按写死的规则回话——这是最早的聊天机器人的做法。
# 本步骤零依赖：不需要网络、不需要 key，人人能跑。

print("嘀——离线版艾芯上线！（本步骤不需要网络和 key）")

print("和它聊聊吧，输入 再见 结束。")
while True:                      # 永远重复执行（Scratch 里的"重复执行"积木）
    user = input("你：")
    if user == "再见":
        print("艾芯：主人再见，我回卫星里继续睡觉了……")
        break                    # 跳出重复执行

    # 规则库：一条 if 一条规则，想到新规则就加一条
    if "你好" in user or "您好" in user:
        reply = "你好呀！我是离线版艾芯，只会按规则回话。"
    elif "名字" in user:
        reply = "我叫艾芯，谐音'爱心'，芯是芯片的芯。"
    elif "天气" in user:
        reply = "我没有联网，不知道天气，也不知道今天几号。"
    elif "垃圾" in user:
        reply = "码力在地面清理过垃圾！那是一段用 Scratch 写成的传奇。"
    elif "1+1" in user or "一加一" in user:
        reply = "1+1 等于 2。这条规则是程序员亲手写死的。"
    else:
        reply = "呃……我的规则库里没有这句话。想教我？去找程序员加一条规则吧。"
    print("艾芯：" + reply)

# 🔍 小实验：
