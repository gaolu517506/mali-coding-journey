# 第 2 课 · 画家的词汇表（步骤 1）：闭集约束
# 今天请 AI 当画家。但 AI 的画怎么"存"进电脑？答案是代码——SVG 画图语言。
# SVG 只认识一张固定的"词汇表"：矩形、圆、椭圆、线条、多边形、文字……
# 词汇表外的词（渐变、阴影、高光……）它画不出来。
# 所以给画家的订单，必须只用词汇表内的词——这叫"闭集约束"。
# 本步骤零依赖：先背词汇表，再玩"订单体检员"。

# ── SVG 词汇表（我们的小画家只认这些）──
VOCAB = {
    "矩形 rect": "画长方形（门、窗、墙、身体）",
    "圆 circle": "画正圆（头、太阳、气球）",
    "椭圆 ellipse": "画扁圆（眼睛、云朵）",
    "线条 line": "画直线（栅栏、雨丝）",
    "多边形 polygon": "画任意直边形状（三角屋顶、星星）",
    "文字 text": "写英文字母或文字",
    "颜色 fill": "纯色填充：red、gold、#FFD700……",
}

print("嘀——画家培训班开课！\n")
print("═ SVG 词汇表（AI 画家唯一会用的积木）═")
for word, use in VOCAB.items():
    print(f"  {word:14s} → {use}")

print("\n═ 订单体检员：下面的画订单，哪些词超纲了？═\n")

# 三份订单（一份合格，两份藏着超纲词）
orders = [
    ("订单 A", "画一个小房子：方形墙、三角屋顶、矩形门、圆形窗，屋顶橙色墙蓝色。"),
    ("订单 B", "画一片梦幻森林，树木要有光泽感，树叶带渐变色，晨雾要有半透明的朦胧感。"),
    ("订单 C", "画一辆卡车：矩形车身、圆形轮子×4、多边形货舱，车身红色轮子黑色。"),
]

BANNED = ["渐变", "阴影", "高光", "光泽", "朦胧", "半透明", "发光", "立体", "质感"]
for name, order in orders:
    found = [w for w in BANNED if w in order]
    if found:
        print(f"{name}：❌ 超纲词 → {'、'.join(found)}（SVG 词汇表里没有，画不出来）")
    else:
        print(f"{name}：✅ 全部在词汇表内，可以开工")

