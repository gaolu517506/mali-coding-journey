# -*- coding: utf-8 -*-
# 第 2 课 · 星图第一笔（步骤 2）：连出北斗七星
# 北斗七星是夜空里最有名的路标——码力升空要靠它导航。
# 我们用一张坐标表 + goto，把七颗星连成一把大勺子。

import turtle

print("嘀——码力启动！")

t = turtle.Turtle()
t.shape("turtle")
t.speed(0)               # 星图作业用极速模式
t.pensize(3)
t.pencolor("deep sky blue")

# 七颗星的坐标表：每颗星是一个装着 [x, y] 两个数的小口袋
# （示意坐标：比例接近真实北斗，不是天文台级别的精确数据）
stars = [
    [170, 60],           # 天枢（勺口第一颗）
    [110, -10],          # 天璇
    [20, 0],             # 天玑
    [-20, 70],           # 天权（勺斗收口）
    [-10, 140],          # 玉衡（勺柄第一颗）
    [-80, 180],          # 开阳
    [-160, 220],         # 摇光（勺柄末端）
]

# 先起飞，空降到第一颗星（天枢）上空，再降落准备连线
t.penup()
t.goto(170, 60)
t.pendown()

# 沿坐标表逐颗连线：for x, y in stars 会一次从口袋里掏出两个数
for x, y in stars:
    t.goto(x, y)         # 飞到这一颗，留下一段航线

# 🔍 小实验：
#    1. 勺子的"斗"还开着口——加一行 t.goto(170, 60) 回到天枢，勺子就闭合了
#    2. 把坐标表里的数字改一改，看勺子会变成什么形状（这就是"编辑星图"）
#    3. 想一想：为什么要先 penup 再 goto 第一颗星？不 penup 会多出哪条线？

turtle.done()            # 让星空窗口保持打开
