# 第 2 课 · 七星变亮（步骤 4）：循环套循环
# 坐标连线只是"路线图"，还不够亮——我们在七颗星的位置各画一颗金色五角星。
# 这需要"外面数星星、里面画星星"的两层循环。

import turtle

print("嘀——码力启动！")

screen = turtle.Screen()
screen.bgcolor("midnight blue")

t = turtle.Turtle()
t.speed(0)
t.hideturtle()
t.pensize(2)

# 北斗七星坐标表（和步骤 2 相同）
stars = [
    [170, 60],           # 天枢
    [110, -10],          # 天璇
    [20, 0],             # 天玑
    [-20, 70],           # 天权
    [-10, 140],          # 玉衡
    [-80, 180],          # 开阳
    [-160, 220],         # 摇光
]

# 外层循环：数星星——每数到一颗，就先飞到它的位置
for x, y in stars:
    t.penup()
    t.goto(x, y)         # 空降到这颗星的位置
    t.pencolor("gold")
    t.pendown()

    # 内层循环：画星星——第 1 课的五角星五步曲（5 条边 × 右转 144°）
    for i in range(5):
        t.forward(50)
        t.right(144)

# 🤔 观察：
#    "画一颗星" = 5 行代码。北斗七颗，靠外层 for 我们只写了这一遍。
#    但是——如果下一个程序想在随机位置也画五角星呢？把这 5 行抄过去？
#    抄 10 份、100 份？改一处星形要满文件找着改？
# 🏭 下一课「函数工厂」开工：把"画一颗星"打包成一块自己的积木，到处可用。

