# 第 2 课 · 瞬移初体验（步骤 1）：起飞与降落
# 上一课的钩子：怎么让海龟"瞬移"到指定位置？
# 答案是 goto——但直接瞬移会把线拖在地上，所以还要先学会"起飞"和"降落"。

import turtle

print("嘀——码力启动！")

t = turtle.Turtle()
t.shape("turtle")
t.speed(3)
t.pensize(3)

# 先画一段航线（降落状态：笔贴着纸，飞过就留痕）
t.forward(150)

# ✈️ 起飞：penup 把笔抬起来——从现在起飞过不留痕
t.penup()
t.forward(100)           # 明明飞了 100，纸上却没有线

# 🌀 空间传送：goto(x, y) 直接飞到坐标 (x, y)
# 坐标规则：屏幕中心是 (0, 0)，往右 x 变大，往上 y 变大
# （Scratch 里的"移到 x y"积木，到 Python 里就是 goto）
t.goto(-150, -100)       # 瞬移到左下角区域

# 🔻 降落：pendown 把笔放回纸上——接下来的飞行又会留下航线
t.pendown()
t.forward(150)           # 第二段航线出现了，和第一段之间隔着一个"跳跃"

# 🔍 小实验：
#    1. 把 t.penup() 那行注释掉（行首加个 #），看看两段航线会怎样——
#       中间会多出一条拖泥带水的线
#    2. 试试 t.goto(0, 0)——一秒回到屏幕中心
#    3. 挑战：用 goto 在屏幕四个角各画一小段航线（提示：角落大约在 ±300、±200）

turtle.done()            # 让星空窗口保持打开
